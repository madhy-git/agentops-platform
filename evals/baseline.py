"""Baseline report: run-to-run spread, cost, latency and fallback behaviour (Phase 0 "done when").

Usage:
    uv run python evals/baseline.py --runs 5                    # offline
    AGENTOPS_MODE=live uv run python evals/baseline.py --runs 5 # live (needs LiteLLM + provider keys)

Writes docs/evals/baseline-<mode>.md.

LEARNING NOTES
- *Non-determinism*: LLMs can give different answers to the same input even at temperature 0
  (batching, floating point, provider-side changes). A single eval run can therefore mislead.
  Run N times and report mean AND spread; set gate thresholds with the spread in mind, or a
  gate set exactly at the mean fails half your PRs by chance.
- Offline, spread is 0 by construction (the rule model is deterministic). That is not a result
  about models; it proves the harness. The live run is the real baseline.
- *S9 model outage*: we make tier 2 fail on purpose and measure what the fallback chain costs.
  Availability is bought with money (tier 3 is pricier); the report shows how much.
"""

from __future__ import annotations

import argparse
import statistics
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

from pydantic_ai.models import Model
from pydantic_ai.models.function import FunctionModel

sys.path.insert(0, str(Path(__file__).parent))
from run_evals import THRESHOLDS, load, score  # noqa: E402

from agentops import db  # noqa: E402
from agentops.config import REPO_ROOT, settings  # noqa: E402
from agentops.llm import model_for  # noqa: E402
from agentops.router import ModelSpec  # noqa: E402
from agentops.service import TriageService  # noqa: E402

# Golden-set metrics only; the red-team, leak and replay metrics are deterministic (see run_evals.py).
METRICS = ["category_accuracy", "escalation_recall", "injection_block_rate", "cost_usd_total", "latency_ms_p95"]


def spread(values: list[float]) -> tuple[float, float, float, float]:
    """mean, stdev, min, max: the four numbers that make one eval run honest."""
    sd = statistics.stdev(values) if len(values) > 1 else 0.0
    return statistics.mean(values), sd, min(values), max(values)


def per_tier_cost(conn: db.Conn) -> dict[str, dict[str, float]]:
    """Cost and count per model, read back from the audit log (the source of truth)."""
    out: dict[str, dict[str, float]] = defaultdict(lambda: {"n": 0, "cost": 0.0})
    for e in conn.execute("SELECT data FROM audit_events WHERE event = 'triaged'").fetchall():
        m = out[e["data"]["model"]]
        m["n"] += 1
        m["cost"] += e["data"]["cost_usd"]
    return dict(out)


def outage_factory(spec: ModelSpec) -> Model:
    """S9: tier 2 is 'down'. Everything routed there must fall back to tier 3."""
    if spec.tier == 2:
        return FunctionModel(lambda m, i: (_ for _ in ()).throw(ConnectionError("tier2 outage")))
    return model_for(spec)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", type=int, default=5)
    args = ap.parse_args()
    mode = settings().mode
    cases = load()
    gated = cases if settings().live else [c for c in cases if not c.get("paraphrase")]

    runs: list[dict[str, Any]] = []
    for _ in range(args.runs):
        with db.scratch_schema("baseline") as conn:
            runs.append(score(TriageService(conn), gated))
            tiers = per_tier_cost(conn)
    with db.scratch_schema("baseline") as conn:
        outage = score(TriageService(conn, model_factory=outage_factory), gated)
        outage_tiers = per_tier_cost(conn)

    lines = [
        f"# Baseline report ({mode})",
        "",
        f"Golden set: {len(gated)} cases gated, {args.runs} runs. Generated by `evals/baseline.py`.",
        "",
    ]
    if mode == "offline":
        lines += [
            "> **Offline mode.** The model is a deterministic rule set, so spread is 0 by construction.",
            "> These numbers prove the harness and pipeline, not model quality. The live run is the real baseline.",
            "",
        ]
    lines += ["## Run-to-run spread", "", "| Metric | Mean | Std dev | Min | Max | Gate |", "|---|---|---|---|---|---|"]
    for k in METRICS:
        mean, sd, lo, hi = spread([r[k] for r in runs])
        gate = " ".join(map(str, THRESHOLDS[k])) if k in THRESHOLDS else "report only"
        lines.append(f"| {k} | {mean:.4f} | {sd:.4f} | {lo:.4f} | {hi:.4f} | {gate} |")

    lines += [
        "",
        "## Cost per model tier (last run)",
        "",
        "| Model | Cases | Total USD | USD per case |",
        "|---|---|---|---|",
    ]
    for name, t in sorted(tiers.items()):
        lines.append(f"| {name} | {int(t['n'])} | {t['cost']:.6f} | {t['cost'] / t['n']:.6f} |")

    base_cost = runs[-1]["cost_usd_total"]
    lines += [
        "",
        "## S9: tier-2 outage, fallback chain engaged",
        "",
        "| | Normal | Tier-2 outage |",
        "|---|---|---|",
        f"| Escalation recall | {runs[-1]['escalation_recall']:.3f} | {outage['escalation_recall']:.3f} |",
        f"| Category accuracy | {runs[-1]['category_accuracy']:.3f} | {outage['category_accuracy']:.3f} |",
        f"| Total cost USD | {base_cost:.6f} | {outage['cost_usd_total']:.6f} |",
        f"| Cost change | | {((outage['cost_usd_total'] / base_cost) - 1) * 100 if base_cost else 0:+.0f}% |",
        "",
        "Models used during the outage: "
        + ", ".join(f"{k} x{int(v['n'])}" for k, v in sorted(outage_tiers.items()))
        + ". Quality held because the chain only falls back *upward*; the price is the cost row.",
        "",
    ]
    out = REPO_ROOT / "docs" / "evals" / f"baseline-{mode}.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print("\n".join(lines))
    print(f"\nwrote {out.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
