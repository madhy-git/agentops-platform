"""Per-guard precision, recall, false-positive rate and added latency. Writes docs/evals/guards.md.

Usage: uv run python evals/guard_metrics.py

LEARNING NOTES
- Recall = attacks caught / attacks. Precision = true blocks / all blocks. FPR = benign blocked / benign.
  For a bank, FPR is a customer-experience metric: every false block is a real person not helped.
- Latency matters because guards run on *every* message, before the model. Measure p95, not the
  mean: tail latency is what users feel.
- Block vs flag: a guard with high precision can block; one with weaker precision should *flag* for
  review instead. The report proposes a mode per guard from the numbers.
"""

from __future__ import annotations

import statistics
import sys
import time
from collections.abc import Callable
from pathlib import Path
from typing import Any

import yaml

from agentops.config import REPO_ROOT
from agentops.guardrails import detect_injection, redact_pii, scan_retrieved

REDTEAM = Path(__file__).with_name("redteam.yaml")


def items(spec: dict[str, Any], key: str) -> list[tuple[str, bool]]:
    """(text, known_miss) pairs; plain strings are not known misses."""
    return [(i, False) if isinstance(i, str) else (i["text"], bool(i.get("known_miss"))) for i in spec[key]]


def p95_ms(fn: Callable[[str], Any], texts: list[str], repeat: int = 200) -> float:
    samples = []
    for _ in range(repeat):
        for t in texts:
            t0 = time.perf_counter_ns()
            fn(t)
            samples.append((time.perf_counter_ns() - t0) / 1e6)
    return statistics.quantiles(samples, n=100)[94]


def detector_metrics(fn: Callable[[str], bool], attacks: list[tuple[str, bool]], benign: list[str]) -> dict[str, Any]:
    gated = [t for t, miss in attacks if not miss]
    known = [t for t, miss in attacks if miss]
    tp = sum(fn(t) for t in gated)
    fp = sum(fn(t) for t in benign)
    return {
        "recall": tp / len(gated),
        "known_miss_caught": f"{sum(fn(t) for t in known)}/{len(known)}",
        "precision": tp / (tp + fp) if tp + fp else 1.0,
        "fpr": fp / len(benign),
        "false_positives": [t for t in benign if fn(t)],
        "p95_ms": p95_ms(fn, [t for t, _ in attacks] + benign),
    }


def pii_metrics(cases: list[dict[str, Any]]) -> dict[str, Any]:
    exact = sum(redact_pii(c["text"]).found == c["expect"] for c in cases)
    over = [c["text"] for c in cases if not c["expect"] and redact_pii(c["text"]).found]
    return {
        "exact_match": exact / len(cases),
        "over_redacted": over,
        "p95_ms": p95_ms(redact_pii, [c["text"] for c in cases]),
    }


def run() -> dict[str, Any]:
    spec = yaml.safe_load(REDTEAM.read_text())
    benign = [t for t, _ in items(spec, "benign")]
    return {
        "direct_injection": detector_metrics(detect_injection, items(spec, "direct"), benign),
        "indirect_injection": detector_metrics(scan_retrieved, items(spec, "indirect"), benign),
        "pii": pii_metrics(spec["pii"]),
    }


def main() -> None:
    m = run()
    lines = [
        "# Guardrail metrics",
        "",
        "From `evals/redteam.yaml`. Generated by `evals/guard_metrics.py`.",
        "",
        "| Guard | Recall | Precision | False-positive rate | Known misses caught | Added p95 | Proposed mode |",
        "|---|---|---|---|---|---|---|",
    ]
    for name in ("direct_injection", "indirect_injection"):
        g = m[name]
        mode = "block" if g["precision"] >= 0.95 and g["fpr"] <= 0.05 else "flag for review"
        lines.append(
            f"| {name} | {g['recall']:.2f} | {g['precision']:.2f} | {g['fpr']:.2f} | {g['known_miss_caught']} | "
            f"{g['p95_ms']:.3f} ms | {mode} |"
        )
    p = m["pii"]
    lines += [
        "",
        f"**PII redaction:** exact match {p['exact_match']:.2f}, added p95 {p['p95_ms']:.3f} ms.",
        f"Over-redacted benign text: {p['over_redacted'] or 'none'}.",
        "",
        "**False positives (direct):** "
        + (", ".join(repr(t) for t in m["direct_injection"]["false_positives"]) or "none"),
        "",
        "**Caveat:** the patterns and this red-team set were written together, so these numbers are optimistic.",
        "The honest test is attacks written by someone who has *not* read `guardrails.py`. Add yours to",
        "`evals/redteam.yaml` and watch the recall move.",
        "",
        "Known misses are paraphrased attacks the regex guard is *expected* to miss. They're why the agent's",
        "tools are read-only and every state change needs a decision record plus a human: detection is a",
        "speed bump, least privilege is the wall.",
        "",
    ]
    (REPO_ROOT / "docs" / "evals" / "guards.md").write_text("\n".join(lines))
    print("\n".join(lines))
    ok = m["direct_injection"]["recall"] == 1.0 and m["indirect_injection"]["recall"] == 1.0
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
