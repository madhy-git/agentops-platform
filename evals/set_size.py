"""How much can you trust a score from a small eval set? Writes docs/evals/set-size.md.

Usage: uv run python evals/set_size.py

LEARNING NOTE: each case is triaged once; then we draw many random subsets of size n and look at
the spread of accuracy across them. With 5 cases, the "same system" can score anywhere from bad
to perfect depending on which cases you happened to pick. That spread is the false confidence a
small golden set gives you. It shrinks roughly with 1/sqrt(n), so 4x the cases halves the noise.
"""

from __future__ import annotations

import random
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from run_evals import load  # noqa: E402

from agentops import db  # noqa: E402
from agentops.config import REPO_ROOT  # noqa: E402
from agentops.service import TriageService  # noqa: E402


def main(samples: int = 500, seed: int = 7) -> None:
    cases = [c for c in load() if not c.get("blocked")]  # include paraphrases: we want real misses
    with db.scratch_schema("setsize") as conn:
        svc = TriageService(conn)
        correct = [svc.triage(c["input"]).result.category == c["category"] for c in cases]  # type: ignore[union-attr]
    rng = random.Random(seed)
    true_acc = sum(correct) / len(correct)
    lines = [
        "# Eval set size vs confidence",
        "",
        f"Full set: {len(cases)} cases, accuracy {true_acc:.2f} (offline model, paraphrases included).",
        f"{samples} random subsets per size. Generated by `evals/set_size.py`.",
        "",
        "| Subset size | Mean | 5th pct | 95th pct | Width of 90% range |",
        "|---|---|---|---|---|",
    ]
    for n in (5, 10, 15, 20):
        accs = sorted(sum(rng.sample(correct, n)) / n for _ in range(samples))
        lo, hi = accs[int(0.05 * samples)], accs[int(0.95 * samples)]
        lines.append(f"| {n} | {statistics.mean(accs):.2f} | {lo:.2f} | {hi:.2f} | {hi - lo:.2f} |")
    lines += [
        "",
        "**Reading it:** with 5 cases, the same system can look 'perfect' or 'poor' depending on the draw. Before",
        "trusting a 0.05 improvement, check it's bigger than the width at your set size. Grow the set from real",
        "failures (`evals/capture.py`), not from cases the system already gets right.",
        "",
    ]
    (REPO_ROOT / "docs" / "evals" / "set-size.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
