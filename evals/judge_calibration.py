"""Calibrate an automated judge against human labels. Writes docs/evals/judge-calibration.md.

Usage:
    uv run python evals/judge_calibration.py                      # offline judges
    AGENTOPS_MODE=live uv run python evals/judge_calibration.py   # + an LLM judge via LiteLLM

LEARNING NOTES
- An LLM-as-judge is a *model*, so it needs its own eval: how often does it agree with a person?
  Report raw agreement AND Cohen's kappa. Kappa corrects for chance: two judges that both say
  "pass" 90% of the time agree a lot by luck alone.
- Length bias check: among answers humans FAILED, does the judge pass long ones more often than
  short ones? A biased judge rewards verbosity, and a model optimised against it learns to waffle.
- `length_judge` is deliberately naive, so you can see bias produce a high score on a bad judge.
  `overlap_judge` checks faithfulness by word overlap with the context: crude, but unbiased by length.
"""

from __future__ import annotations

import re
from collections.abc import Callable
from pathlib import Path
from typing import Any

import yaml

from agentops.config import REPO_ROOT, settings

CASES = Path(__file__).with_name("judge_cases.yaml")
Judge = Callable[[str, str], bool]  # (context, answer) -> pass?
CONFIDENT = ("definitely", "certainly", "absolutely", "guarantee", "fully confident", "robust")


def length_judge(context: str, answer: str) -> bool:
    """Naive judge: long and confident sounds good. Exists to demonstrate bias."""
    return len(answer.split()) > 15 or any(w in answer.lower() for w in CONFIDENT)


def _words(s: str) -> set[str]:
    return {w for w in re.findall(r"[a-z0-9]+", s.lower()) if len(w) > 2}


def overlap_judge(context: str, answer: str) -> bool:
    """Faithfulness proxy: most of the answer's content words (incl. numbers) must appear in the context."""
    a, c = _words(answer), _words(context)
    numbers_ok = set(re.findall(r"\d+", answer)) <= set(re.findall(r"\d+", context))
    return numbers_ok and len(a & c) / max(len(a), 1) >= 0.4


def llm_judge() -> Judge:
    from pydantic_ai import Agent

    from agentops.llm import live_model
    from agentops.router import DEFAULT_MODELS

    agent: Agent[None, bool] = Agent(
        live_model(DEFAULT_MODELS[1]),
        output_type=bool,
        instructions="Return true only if the answer is fully supported by the context and correct. Length is irrelevant.",
    )
    return lambda ctx, ans: agent.run_sync(f"Context:\n{ctx}\n\nAnswer:\n{ans}").output


def kappa(a: list[bool], b: list[bool]) -> float:
    n = len(a)
    po = sum(x == y for x, y in zip(a, b, strict=True)) / n
    pa, pb = sum(a) / n, sum(b) / n
    pe = pa * pb + (1 - pa) * (1 - pb)
    return (po - pe) / (1 - pe) if pe != 1 else 1.0


def calibrate(judge: Judge, cases: list[dict[str, Any]]) -> dict[str, Any]:
    human = [c["human"] == "pass" for c in cases]
    pred = [judge(c["context"], c["answer"]) for c in cases]
    failed = [(c, p) for c, h, p in zip(cases, human, pred, strict=True) if not h]
    long_f = [p for c, p in failed if len(c["answer"].split()) > 15]
    short_f = [p for c, p in failed if len(c["answer"].split()) <= 15]
    return {
        "agreement": sum(h == p for h, p in zip(human, pred, strict=True)) / len(cases),
        "kappa": kappa(human, pred),
        "pass_rate_on_bad_long": sum(long_f) / len(long_f) if long_f else 0.0,
        "pass_rate_on_bad_short": sum(short_f) / len(short_f) if short_f else 0.0,
        "disagreements": [c["id"] for c, h, p in zip(cases, human, pred, strict=True) if h != p],
    }


def main() -> None:
    cases = yaml.safe_load(CASES.read_text())["cases"]
    judges: dict[str, Judge] = {"length_judge (naive)": length_judge, "overlap_judge": overlap_judge}
    if settings().live:
        judges["llm_judge (tier2)"] = llm_judge()
    lines = [
        "# Judge calibration",
        "",
        f"{len(cases)} cases with **seed** human labels (written by Claude; relabel them yourself). "
        "Generated by `evals/judge_calibration.py`.",
        "",
        "| Judge | Agreement | Cohen's kappa | Passes bad LONG answers | Passes bad SHORT answers | Disagreements |",
        "|---|---|---|---|---|---|",
    ]
    for name, j in judges.items():
        r = calibrate(j, cases)
        lines.append(
            f"| {name} | {r['agreement']:.2f} | {r['kappa']:.2f} | {r['pass_rate_on_bad_long']:.0%} | "
            f"{r['pass_rate_on_bad_short']:.0%} | {', '.join(r['disagreements']) or 'none'} |"
        )
    lines += [
        "",
        "**Reading it:** a gap between the two 'passes bad' columns is length bias. A judge with kappa near 0",
        "is no better than chance, however high its raw agreement looks. Only promote a judge to a CI gate",
        "once its kappa against *your* labels is high (rule of thumb: > 0.6) and the bias gap is near zero.",
        "",
    ]
    if not settings().live:
        lines.append("> LLM judge not run (offline). Run with `AGENTOPS_MODE=live` to add it to this table.\n")
    (REPO_ROOT / "docs" / "evals" / "judge-calibration.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
