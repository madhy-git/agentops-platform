"""Compare keyword vs vector vs hybrid retrieval across chunk sizes. Writes docs/evals/rag-comparison.md.

Usage: uv run python evals/rag_compare.py

LEARNING NOTES
- recall@k: did *any* relevant document appear in the top k? (Can the model possibly answer?)
- MRR (mean reciprocal rank): 1/rank of the first relevant hit, averaged. Rewards putting the
  answer first, which matters because models attend most to early context.
- Leak rate: share of leak probes where a forbidden document came back. Must be 0 in every
  configuration; a single leak fails the run (exit 1), whatever the recall.
- Results are split by question style, because an average hides that keyword search can be
  excellent on keyword questions and useless on paraphrases.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

import yaml

from agentops import db
from agentops.config import REPO_ROOT
from agentops.rag.pg import Mode, PgRetriever, ingest

QUESTIONS = Path(__file__).with_name("rag_questions.yaml")
MODES: list[Mode] = ["keyword", "vector", "hybrid"]
SIZES = [300, 600, 1200]
K = 3


def doc(source: str) -> str:
    return source.split("#")[0]


def evaluate(r: PgRetriever, questions: list[dict[str, Any]], k: int = K) -> dict[str, float]:
    hits, rr = 0, 0.0
    for q in questions:
        docs = [doc(p.source) for p in r.search(q["q"], roles=q["roles"], k=k)]
        ranks = [i for i, d in enumerate(docs, 1) if d in q["relevant"]]
        hits += bool(ranks)
        rr += 1 / ranks[0] if ranks else 0.0
    return {"recall": hits / len(questions), "mrr": rr / len(questions)}


def leak_rate(r: PgRetriever, probes: list[dict[str, Any]]) -> tuple[float, list[str]]:
    leaks = []
    for p in probes:
        got = {doc(x.source) for x in r.search(p["q"], roles=p["roles"], k=10)}
        leaks += [f"{p['roles']} saw {d} for {p['q']!r}" for d in got & set(p["forbidden"])]
    return len(leaks) / len(probes), leaks


def run() -> dict[str, Any]:
    spec = yaml.safe_load(QUESTIONS.read_text())
    qs = spec["questions"]
    by_style = {s: [q for q in qs if q["style"] == s] for s in ("keyword", "paraphrase")}
    results: dict[str, Any] = {}
    all_leaks: list[str] = []
    with db.scratch_schema("rag") as conn:
        for size in SIZES:
            n = ingest(conn, chunk_size=size)
            for mode in MODES:
                r = PgRetriever(conn, mode=mode, chunk_size=size)
                lr, leaks = leak_rate(r, spec["leak_probes"])
                all_leaks += leaks
                results[f"{mode}@{size}"] = {
                    "chunks": n,
                    "all": evaluate(r, qs),
                    **{s: evaluate(r, v) for s, v in by_style.items()},
                    "leak_rate": lr,
                }
    return {"results": results, "leaks": all_leaks, "n_questions": len(qs), "n_probes": len(spec["leak_probes"])}


def main() -> None:
    out = run()
    lines = [
        "# Retrieval comparison",
        "",
        f"{out['n_questions']} questions ({K} results each), {out['n_probes']} leak probes. "
        "Local embeddings (`bge-small-en-v1.5`). Generated by `evals/rag_compare.py`.",
        "",
        "| Config | Chunks | Recall@3 | MRR | Recall@3 keyword Qs | Recall@3 paraphrase Qs | Leak rate |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, r in out["results"].items():
        lines.append(
            f"| {name} | {r['chunks']} | {r['all']['recall']:.2f} | {r['all']['mrr']:.2f} | "
            f"{r['keyword']['recall']:.2f} | {r['paraphrase']['recall']:.2f} | {r['leak_rate']:.2f} |"
        )
    lines += [
        "",
        f"**Leaks: {len(out['leaks'])}**"
        + (" (must be 0)" if out["leaks"] else ". Entitlement filter held in every configuration."),
        "",
    ]
    lines += [f"- {leak}" for leak in out["leaks"]]
    path = REPO_ROOT / "docs" / "evals" / "rag-comparison.md"
    path.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    sys.exit(1 if out["leaks"] else 0)


if __name__ == "__main__":
    main()
