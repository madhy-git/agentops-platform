"""Framework benchmark: same golden set through each adapter, N runs. Writes docs/evals/framework-benchmark.md.

Usage:
    uv sync --extra bench
    uv run python -m benchmarks.run --runs 5
    AGENTOPS_MODE=live uv run python -m benchmarks.run --runs 5     # real quality and cost via LiteLLM

LEARNING NOTE: report spread (several runs), cost and latency, not a single accuracy number. Offline, accuracy
must be identical across frameworks (same stand-in rules), so any gap is an adapter bug; the interesting
numbers offline are framework overhead and token counts (one model call in the graph vs a tool loop).
"""

from __future__ import annotations

import argparse
import inspect
import json
import statistics

from agentops.config import REPO_ROOT, settings

from .adapters import ADAPTERS, SPEC

GOLDEN = REPO_ROOT / "evals" / "golden.jsonl"


def cases() -> list[dict]:
    rows = [json.loads(line) for line in GOLDEN.read_text().splitlines() if line.strip()]
    rows = [r for r in rows if not r.get("blocked")]  # guardrails aren't part of the framework comparison
    return rows if settings().live else [r for r in rows if not r.get("paraphrase")]


def pct(values: list[float], q: int) -> float:
    return statistics.quantiles(values, n=100)[q - 1] if len(values) > 1 else values[0]


def run_adapter(cls: type, golden: list[dict], runs: int) -> dict:
    adapter = cls()
    accs, recalls, lat, tokens = [], [], [], []
    for _ in range(runs):
        ok = esc_ok = esc_n = 0
        for c in golden:
            r = adapter.triage(c["input"])
            ok += r.output.category == c["category"]
            if c["needs_human"]:
                esc_n += 1
                esc_ok += r.output.needs_human
            lat.append(r.latency_ms)
            tokens.append(r.input_tokens + r.output_tokens)
        accs.append(ok / len(golden))
        recalls.append(esc_ok / esc_n)
    loc = len(inspect.getsource(cls).splitlines())
    return {
        "accuracy_mean": statistics.mean(accs), "accuracy_sd": statistics.pstdev(accs),
        "recall_mean": statistics.mean(recalls), "recall_sd": statistics.pstdev(recalls),
        "p50_ms": pct(lat, 50), "p95_ms": pct(lat, 95),
        "tokens_per_case": statistics.mean(tokens),
        "usd_per_1k_cases": statistics.mean(tokens) * SPEC.usd_per_1k_tokens,  # tokens/1000 * price * 1000 cases
        "adapter_loc": loc,
    }  # fmt: skip


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", type=int, default=5)
    args = ap.parse_args()
    golden = cases()
    results = {cls.name: run_adapter(cls, golden, args.runs) for cls in ADAPTERS}
    mode = settings().mode
    lines = [
        f"# Framework benchmark ({mode})",
        "",
        f"{len(golden)} golden cases × {args.runs} runs, model alias `{SPEC.name}`. Generated by `benchmarks/run.py`.",
        "",
        "| Framework | Accuracy (mean ± sd) | Escalation recall | p50 ms | p95 ms | Tokens / case | USD / 1k cases | Adapter LOC |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for name, r in results.items():
        lines.append(
            f"| {name} | {r['accuracy_mean']:.3f} ± {r['accuracy_sd']:.3f} | {r['recall_mean']:.3f} ± {r['recall_sd']:.3f} | "
            f"{r['p50_ms']:.1f} | {r['p95_ms']:.1f} | {r['tokens_per_case']:.0f} | {r['usd_per_1k_cases']:.2f} | {r['adapter_loc']} |"
        )
    if mode == "offline":
        lines += [
            "",
            "> **Offline:** both frameworks drive the same rule-based stand-in, so equal accuracy is *expected* (a gap would be",
            "> an adapter bug). Latency here is framework overhead only, and offline token counts are approximations",
            "> (the LangGraph stand-in counts words). Run live for real quality, cost and latency.",
        ]
    lines += [
        "",
        "**Finding:** the first run gave LangGraph escalation recall **0.923**: the fixed graph had no case-lookup step, so a",
        "vulnerable customer (C-1002) wasn't escalated. The agent loop got it right because the *model* chose to call",
        "`lookup_case`. Fixed by adding a conditional `lookup` node. In a graph, every capability must be explicit.",
        "",
        "**Design difference, not just speed:** PydanticAI runs an agent loop (the model chooses to call `search_policy`, then",
        "answers: 2+ model turns); the LangGraph version is a fixed `retrieve -> classify` graph (1 model call, plus a conditional lookup node). The graph is",
        "cheaper and easier to audit; the loop can decide to look up a case. Choose per use case.",
        "",
    ]
    out = REPO_ROOT / "docs" / "evals" / "framework-benchmark.md"
    out.write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
